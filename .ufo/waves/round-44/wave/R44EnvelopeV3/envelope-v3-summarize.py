#!/usr/bin/env python3
"""Consolidated evidence for seat R44EnvelopeV3: driver receipts + live extras, as one table set."""
import os
import pathlib
import re
import shutil
import subprocess
import sys

S = pathlib.Path(sys.argv[1])
DRAFT = sys.argv[2]
OLD = sys.argv[3]
W = S / "work"


def envelope_lines(text):
    return [ln for ln in text.splitlines() if ln.startswith("ENVELOPE start") or ln.startswith("ENVELOPE end")
            or ln.startswith("ENVELOPE measurement")]


def summarize(text):
    m = re.search(r"local_bin_content_before=(\S+?) after=(\S+?) (unchanged|CHANGED)", text)
    rc = re.search(r"^RC=(\d+)$", text, re.M)
    if m:
        return m.group(1), m.group(2), m.group(3), rc.group(1) if rc else "?"
    return "-", "-", "DIGEST-ERROR", rc.group(1) if rc else "?"


def case(cid):
    return summarize((W / cid / "out.txt").read_text())


def ctl(cid):
    return summarize((W / (cid + ".txt")).read_text())


print("envelope v3 (seat R44EnvelopeV3) — consolidated evidence, generated by summarize.py")
print("draft  sha256 =%s" % subprocess.run(["sha256sum", DRAFT], capture_output=True, text=True).stdout.split()[0])
print("old    sha256 =%s  (round-43 claims/envelope.sh with ONE token remapped: the digest cd target honours"
      % subprocess.run(["sha256sum", OLD], capture_output=True, text=True).stdout.split()[0])
print("               ENVELOPE_BINDIR instead of the literal path, so both scripts watch the same fixture)")
print()
print("## A. the six routed mutations — red/green, v3 vs round-43 envelope")
print("   fixture per case, built fresh: real-tool f755, plain f644, secret f000, link-tool -> real-tool,")
print("   sub/, broken -> /nonexistent-target, loop -> loop, dirlink -> sub, fifo.  Mutation runs INSIDE the envelope.")
print()
for cid, what in [("M1", "content rewrite of an existing entry"), ("M2", "new file in the watched dir"),
                  ("M3", "symlink retargeted"), ("M4", "chmod 700 plain (mode-only, same bytes)"),
                  ("M5", "mode-000 entry rewritten, mode restored to 000"), ("M6", "xattr user.tag set")]:
    nb, na, nst, nrc = case("new-" + cid)
    ob, oa, ost, orc = case("old-" + cid)
    print("%s  %s" % (cid, what))
    print("    v3   %-10s rc=%s   before=%s after=%s" % (nst, nrc, nb, na))
    print("    old  %-10s rc=%s   before=%s after=%s" % (ost, orc, ob, oa))
print()
print("## B. v3-only extras (not part of the six; ungated improvements)")
for cid, what in [("M8", "new file nested under an existing subdir (old stops at depth 1)"),
                  ("M9", "mode flip of the watched dir itself")]:
    nb, na, nst, nrc = case("new-" + cid)
    ob, oa, ost, orc = case("old-" + cid)
    print("%s  %-58s v3 %-9s rc=%s | old %-9s rc=%s" % (cid, what, nst, nrc, ost, orc))
print()
print("## C. negative controls (must NOT fire)")
for cid, what in [("nc-repeat", "rich fixture, no mutation (whole digest must be equal)"),
                  ("nc-exit", "rich fixture, command /bin/false (rc must propagate)"),
                  ("nc-absent", "watched dir missing (old parity: 'absent', no change)"),
                  ("nc-symlinkroot", "watched path is a symlink to a directory"),
                  ("nc-file", "watched path is a regular file (loud INVALID, not silent)"),
                  ("m7", "watched symlink retargeted at a byte-identical tree")]:
    b, a, st, rc = ctl(cid) if cid != "m7" else case("m7")
    print("%-15s %-52s %-10s rc=%s" % (cid, what, st, rc))
print()
print("## D. real watched dir /home/vgpnk/.local/bin, default target, /bin/true inside")
for cid, label in [("real", "v3"), ("oldreal", "old")]:
    text = (W / (cid + ".txt")).read_text()
    b, a, st, rc = summarize(text)
    wall = re.search(r"REAL_WALL_MS=(\d+)", text)
    print("%-8s %-10s %-18s -> %-18s rc=%s wall_ms=%s" % (label, st, b, a, rc, wall.group(1) if wall else "?"))
    for ln in envelope_lines(text):
        print("    " + ln)
print()
print("## E. v3 against a fixture dir, live runs (escaped names, stealth rewrite, missing python3)")
X = S / "extra"
shutil.rmtree(X, ignore_errors=True)


def fresh(name, entries):
    d = X / name
    d.mkdir(parents=True)
    for rel, payload, extra in entries:
        p = d / rel
        if extra == "symlink":
            p.parent.mkdir(parents=True, exist_ok=True)
            p.symlink_to(payload)
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(payload)
            if extra:
                os.chmod(p, extra)
    return d


def run(tag, target, cmd, scr, env_extra=None):
    scr.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ, ENVELOPE_BINDIR=str(target), **(env_extra or {}))
    p = subprocess.run(cmd, env=env, capture_output=True, text=True)
    print("%s  rc=%s" % (tag, p.returncode))
    for ln in envelope_lines(p.stdout):
        print("    " + ln)
    if p.stderr.strip():
        print("    stderr: " + p.stderr.strip().splitlines()[0])
    return p


weird = fresh("weird", [("sub/tab\there", "a", None), ("sub/nl\nhere", "b", None), ("plain", "c", None)])
run("E1 weird names, no mutation", weird, [DRAFT, str(X / "e1"), "/bin/true"], X / "e1")
run("E2 weird names, no mutation (repeat, must equal E1)", weird, [DRAFT, str(X / "e2"), "/bin/true"], X / "e2")
run("E3 rename a tab-named entry",
    weird, [DRAFT, str(X / "e3"), "/bin/sh", "-c", "mv '%s' '%s'" % (weird / "sub" / "tab\there", weird / "sub" / "tab\there2")],
    X / "e3")
stealth = fresh("stealth", [("same", "identical\n", None)])
os.utime(stealth / "same", (1_600_000_000, 1_600_000_000))
run("E4 same bytes rewritten, mtime restored with touch -d (ctime moves)",
    stealth,
    [DRAFT, str(X / "e4"), "/bin/sh", "-c",
     "printf identical\\\\n > '%s'; touch -d @1600000000 '%s'" % (stealth / "same", stealth / "same")],
    X / "e4")
nopy = S / "envelope-nopy.sh"
nopy.write_text(pathlib.Path(DRAFT).read_text().replace("  python3 -I - ", "  python3-not-installed -I - "))
os.chmod(nopy, 0o755)
run("E5 digest tool missing (copy with one token remapped) — must be loud",
    weird, [str(nopy), str(X / "e5"), "/bin/true"], X / "e5")
print()
print("## F. digest-body excerpt (fields: path kind mode nlink size mtime_ns ctime_ns ino link xattr content)")
body = subprocess.run(["python3", "-I", "-", str(W / "new-M4" / "target")],
                      stdin=open(S / "digest-prog.py"), capture_output=True, text=True)
print(body.stdout.rstrip())
