import importlib.util, os, shutil, subprocess
from pathlib import Path
LANE=Path('/home/vgpnk/Projects/shokunin/kengaku-shokunin')
spec=importlib.util.spec_from_file_location('c2', LANE/'plans/round53_c2_tipstate.py')
c2=importlib.util.module_from_spec(spec); spec.loader.exec_module(c2)
root=Path('/fast/scratch/hyaku/kengaku-r53/C2RevCounter/t/w9'); shutil.rmtree(root, ignore_errors=True); root.mkdir(parents=True)
d=root/'src'; d.mkdir()
subprocess.run(['git','-C',str(d),'init','-q','-b','main'],check=True)
(d/'f.txt').write_text('v1'); subprocess.run(['git','-C',str(d),'add','-A'],check=True)
subprocess.run(['git','-C',str(d),'-c','user.email=a@b','-c','user.name=a','commit','-qm','one'],check=True)
w=c2.Worker(d, root/'work', 0)
print("clone HEAD:", subprocess.run(['git','-C',str(w.dir),'rev-parse','HEAD'],capture_output=True,text=True).stdout.strip()[:8])
print("--- row 1 commits in the clone (moves HEAD) ---")
subprocess.run(['git','-C',str(w.dir),'config','user.email','a@b'],check=True)
subprocess.run(['git','-C',str(w.dir),'config','user.name','a'],check=True)
(w.dir/'LEAKED.txt').write_text('x')
subprocess.run(['git','-C',str(w.dir),'add','-A'],check=True)
subprocess.run(['git','-C',str(w.dir),'commit','-qm','row1-committed'],check=True)
print("clone HEAD now:", subprocess.run(['git','-C',str(w.dir),'rev-parse','HEAD'],capture_output=True,text=True).stdout.strip()[:8])
print("--- Worker.reset ---")
w.reset()
print("HEAD after reset:", subprocess.run(['git','-C',str(w.dir),'rev-parse','HEAD'],capture_output=True,text=True).stdout.strip()[:8])
print("LEAKED.txt (committed by row 1) still present after reset:", (w.dir/'LEAKED.txt').exists())
print("git status after reset:", repr(subprocess.run(['git','-C',str(w.dir),'status','--porcelain'],capture_output=True,text=True).stdout))
print()
print("--- nested repo left by a row ---")
w2=c2.Worker(d, root/'work2', 0)
subprocess.run(['git','-C',str(w2.dir/'nested'),'init','-q'],check=True) if (w2.dir/'nested').mkdir(exist_ok=True) is None else None
w2.reset()
print("nested repo survives reset:", (w2.dir/'nested'/'.git').exists())
