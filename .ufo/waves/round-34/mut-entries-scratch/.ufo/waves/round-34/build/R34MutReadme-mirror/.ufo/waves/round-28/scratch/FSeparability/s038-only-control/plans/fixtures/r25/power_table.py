#!/usr/bin/env python3
"""power_table.py — round-25 power table for the frozen two-sided 95% Clopper-Pearson rule.

Pre-registration: plans/round-25-claims.md:35-45 (C1). An estimate with k correct of n is
PASS iff its two-sided 95% Clopper-Pearson (CP) lower bound is >= the bar. Registered power
ask: with zero errors the lower bound is 0.025^(1/n), first >= 0.80 at n = 17.

One TSV, blank-line separated blocks, each opened by its own `table` header row:
  min_n       bars 0.80/0.90/0.95 x errors e = 0/1/2 (k = n - e): the minimum n whose CP lower
              bound >= bar, the bound and the exact decision tail at min_n and min_n - 1, and
              the rule-of-three / Wilson minima beside it (approximations, never verdicts).
  zero_error  n = 1..40: zero-error CP lower bound, the rule-of-three approximation 1 - 3/n,
              their difference, and the one-sided 95% bound 0.05^(1/n) the rule approximates.
  derived     findings computed from the blocks above.
  check       assertions; any FAIL exits 1. power_ask_n17 is the registered power ask.

Exactness. For X ~ Binomial(n, p) and 1 <= k <= n, P(X >= k) strictly increases in p and the
CP lower bound p_L(k, n) is the p where it equals alpha/2, so
    p_L(k, n) >= bar   <=>   P(X >= k | n, bar) <= alpha/2.
Every decision is that comparison in integer arithmetic: no floating point, no Beta quantile.
Printed bounds come from a 64-step integer bisection bracket lo <= p_L < hi, hi - lo = 2^-64,
and print only when both ends round (half-even) to the same digits. p_L grows with n at fixed
e, so the first passing n is the minimum (check no_pass_reversal re-confirms to n = 400);
"at most e errors" binds at exactly e errors since p_L grows with k at fixed n. Wilson
(z = 1.959963984540054) and the 0.025^(1/n) closed form are floats, cleared by >= 1e-9.

Usage (from the lane root; stdlib only, offline):
  python3 plans/fixtures/r25/power_table.py              print the TSV
  python3 plans/fixtures/r25/power_table.py --write      write power_table.tsv beside this file
  python3 plans/fixtures/r25/power_table.py --check      regenerate and byte-compare that file
  python3 plans/fixtures/r25/power_table.py --summary    one counting line
  python3 plans/fixtures/r25/power_table.py --selftest   positive controls + red mutation runs
Exit: 0 = every check PASS (and, for --check, no drift); 1 = a check FAIL, drift, or a selftest
failure; 2 = usage.
"""

import argparse
import math
import sys
from collections import namedtuple
from fractions import Fraction
from pathlib import Path

HALF_ALPHA = Fraction(1, 40)  # frozen rule: two-sided alpha = 0.05 -> 0.025 per tail
ONE_SIDED_HALF_ALPHA = Fraction(1, 20)  # one-sided 95% (= two-sided 90%)
BARS = (Fraction(4, 5), Fraction(9, 10), Fraction(19, 20))
ERRORS = (0, 1, 2)
ZERO_ERROR_NS = range(1, 41)
POWER_ASK = (Fraction(4, 5), 0, 17)  # bar, errors, registered min n (round-25-claims.md:42-45)
EXTENDED_ERRORS = range(6)  # N(e) at the power-ask bar for e = 0..5
RULE3 = 3
WINDOW = 400  # every scanned minimum is re-checked for reversal up to this n
BITS = 64  # bisection bracket width 2^-BITS
PLACES = 6
TAIL_PLACES = 8
Z95 = 1.959963984540054
FLOAT_CLEARANCE = 1e-9
TSV_PATH = Path(__file__).with_name("power_table.tsv")

# R binom.test(k, n)$conf.int as printed (7 significant digits): positive controls only.
R_REFERENCE = {(9, 10): ("0.5549839", "0.9974714"), (10, 10): ("0.6915029", "1.0000000")}

HEADER = (
    "# power_table.tsv - generated by `python3 plans/fixtures/r25/power_table.py --write`; never hand-edited.",
    "# Frozen rule plans/round-25-claims.md:35-45: PASS iff the two-sided 95% Clopper-Pearson lower bound >= bar"
    " (alpha/2 = 0.025 per tail).",
    "# Decisions are exact integer tests tail = P(X >= k | n, p = bar) <= 0.025. Bounds: 6 dp certified by a"
    " 2^-64 bisection bracket. Tails: exact, 8 dp.",
    "# rule3 = 1 - 3/n (rule of three; negative = vacuous) and Wilson (z = 1.959963984540054, float) are"
    " approximations, never verdicts.",
    "# Zero errors: the CP upper bound is 1, so every non-PASS zero-error verdict is INDETERMINATE (FAIL impossible).",
)
COLUMNS = {
    "min_n": (
        "bar", "errors", "min_n", "counts", "cp_lower_at_min_n", "cp_lower_at_min_n-1",
        "tail_at_min_n", "tail_at_min_n-1", "rule3_min_n", "wilson_min_n",
    ),
    "zero_error": (
        "n", "cp_lower", "rule3_1-3/n", "rule3_minus_cp", "cp_lower_1sided95", "cp_PASS_at", "rule3_PASS_at",
    ),
    "derived": ("name", "value"),
    "check": ("name", "status", "detail"),
}

Bound = namedtuple("Bound", "lo hi text")


def tail_scaled(k, n, a, b):
    """b**n * P(X >= k) for X ~ Binomial(n, a/b), as an exact integer."""
    return sum(math.comb(n, j) * a**j * (b - a) ** (n - j) for j in range(max(k, 0), n + 1))


def upper_tail(k, n, p):
    """P(X >= k | n, p) for rational p, exactly."""
    p = Fraction(p)
    return Fraction(tail_scaled(k, n, p.numerator, p.denominator), p.denominator**n)


def cp_passes(k, n, bar, half_alpha=HALF_ALPHA):
    """Frozen-rule decision, exact: is the CP lower bound of k/n >= bar?"""
    if k <= 0:
        return bar <= 0  # p_L(0, n) = 0
    return upper_tail(k, n, bar) <= half_alpha


def cp_lower_bracket(k, n, half_alpha=HALF_ALPHA, bits=BITS):
    """(lo, hi) with lo <= p_L(k, n) < hi and hi - lo = 2^-bits; p_L(0, n) = 0 exactly."""
    if k <= 0:
        return Fraction(0), Fraction(0)
    scale = 1 << bits
    limit = half_alpha.numerator * scale**n
    lo, hi = 0, scale  # invariant: P(X >= k | lo) <= half_alpha < P(X >= k | hi)
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if tail_scaled(k, n, mid, scale) * half_alpha.denominator <= limit:
            lo = mid
        else:
            hi = mid
    return Fraction(lo, scale), Fraction(hi, scale)


def dec(x, places=PLACES):
    """Exact decimal text of a rational, rounded half-even at `places`."""
    q = round(Fraction(x) * 10**places)
    sign = "-" if q < 0 else ""
    q = abs(q)
    return f"{sign}{q // 10**places}.{q % 10**places:0{places}d}"


def certify(lo, hi, places=PLACES):
    """Digits every value in [lo, hi] rounds to (dec is monotone), or None when they differ."""
    a, b = dec(lo, places), dec(hi, places)
    return a if a == b else None


def certified_text(lo, hi, label, uncertified):
    text = certify(lo, hi)
    if text is None:
        uncertified.append(label)
        text = f"{dec(lo)}..{dec(hi)}"
    return text


def bound(k, n, half_alpha, uncertified):
    lo, hi = cp_lower_bracket(k, n, half_alpha)
    return Bound(lo, hi, certified_text(lo, hi, f"{k}/{n}@{half_alpha}", uncertified))


def wilson_lower(k, n, z=Z95):
    """Wilson score lower bound, float: sensitivity column only, never a verdict."""
    p = k / n
    z2 = z * z
    centre = p + z2 / (2 * n)
    half = z * math.sqrt(p * (1 - p) / n + z2 / (4 * n * n))
    return (centre - half) / (1 + z2 / n)


def first_pass(passes, start, stop=WINDOW):
    """(smallest n in [start, stop] with passes(n), or None; the later n that fail again)."""
    first = next((n for n in range(start, stop + 1) if passes(n)), None)
    if first is None:
        return None, []
    return first, [n for n in range(first + 1, stop + 1) if not passes(n)]


def cp_min_n(bar, e, half_alpha=HALF_ALPHA):
    return first_pass(lambda n: cp_passes(n - e, n, bar, half_alpha), e + 1)


def spans(ns):
    """[15, 16, 30, 31] -> '15-16,30-31'; [] -> 'none'."""
    out, ns, i = [], sorted(ns), 0
    while i < len(ns):
        j = i
        while j + 1 < len(ns) and ns[j + 1] == ns[j] + 1:
            j += 1
        out.append(str(ns[i]) if i == j else f"{ns[i]}-{ns[j]}")
        i = j + 1
    return ",".join(out) or "none"


def power_ask_check(found, half_alpha=HALF_ALPHA):
    """The registered ask holds iff the scan found it and it is exactly the first passing n."""
    bar, e, n = POWER_ASK
    t_at, t_prev = upper_tail(n - e, n, bar), upper_tail(n - 1 - e, n - 1, bar)
    ok = found == n and t_at <= half_alpha < t_prev
    detail = (
        f"scan min_n(bar {dec(bar, 2)}, e={e})={found}, registered {n}; "
        f"P(X>={n - e}|{n},{dec(bar, 2)})={dec(t_at, TAIL_PLACES)} <= {dec(half_alpha, 3)} < "
        f"P(X>={n - 1 - e}|{n - 1},{dec(bar, 2)})={dec(t_prev, TAIL_PLACES)}"
    )
    return ok, detail


def build():
    """Every block of the table plus its checks; deterministic."""
    unc, reversals, disagree, ties = [], [], [], []
    min_rows, gaps, minima = [], [], {}
    for bar in BARS:
        tag = dec(bar, 2)
        for e in ERRORS:
            n_min, rev = cp_min_n(bar, e)
            reversals += [f"cp {tag} e={e} n={spans(rev)}"] if rev else []
            at = bound(n_min - e, n_min, HALF_ALPHA, unc)
            prev = bound(n_min - 1 - e, n_min - 1, HALF_ALPHA, unc)
            if not (at.lo >= bar and prev.hi <= bar):
                disagree.append(f"{tag} e={e}")
            above = certified_text(at.lo - bar, at.hi - bar, f"gap {tag} e={e}", unc)
            below = certified_text(bar - prev.hi, bar - prev.lo, f"gap {tag} e={e}", unc)
            gaps.append((at.lo - bar, f"bar {tag} e={e}: lower({n_min - e}/{n_min})={at.text}, {above} above"))
            gaps.append((bar - prev.hi, f"bar {tag} e={e}: lower({n_min - 1 - e}/{n_min - 1})={prev.text}, {below} below"))
            r3_min = "NA"
            if e == 0:
                r3_min, rev = first_pass(lambda n: 1 - Fraction(RULE3, n) >= bar, 1)
                reversals += [f"rule3 {tag} n={spans(rev)}"] if rev else []
            w_min, rev = first_pass(lambda n: wilson_lower(n - e, n) >= float(bar), e + 1)
            reversals += [f"wilson {tag} e={e} n={spans(rev)}"] if rev else []
            ties += [
                f"wilson {tag} e={e} n={n}"
                for n in (w_min - 1, w_min)
                if n > 0 and abs(wilson_lower(n - e, n) - float(bar)) < FLOAT_CLEARANCE
            ]
            minima[(bar, e)] = n_min
            min_rows.append((
                tag, str(e), str(n_min), f"{n_min - e}/{n_min}", at.text, prev.text,
                dec(upper_tail(n_min - e, n_min, bar), TAIL_PLACES),
                dec(upper_tail(n_min - 1 - e, n_min - 1, bar), TAIL_PLACES),
                str(r3_min), str(w_min),
            ))

    zero_rows, r3_above, r3_under_one_sided, max_dev = [], [], [], 0.0
    false_pass = {bar: [] for bar in BARS}
    for n in ZERO_ERROR_NS:
        two = bound(n, n, HALF_ALPHA, unc)
        one = bound(n, n, ONE_SIDED_HALF_ALPHA, unc)
        r3 = 1 - Fraction(RULE3, n)
        diff = certified_text(r3 - two.hi, r3 - two.lo, f"rule3-cp n={n}", unc)
        if r3 >= two.hi:  # hi > p_L, so the rule of three is strictly the larger bound
            r3_above.append(n)
        if r3 < one.lo:
            r3_under_one_sided.append(n)
        max_dev = max(max_dev, abs(float(HALF_ALPHA) ** (1 / n) - float(two.lo)))
        cp_bars = [bar for bar in BARS if cp_passes(n, n, bar)]
        r3_bars = [bar for bar in BARS if r3 >= bar]
        zero_rows.append((
            str(n), two.text, dec(r3), diff, one.text,
            ",".join(dec(b, 2) for b in cp_bars) or "none",
            ",".join(dec(b, 2) for b in r3_bars) or "none",
        ))

    w_above = []
    for n in range(1, WINDOW + 1):
        w, c = wilson_lower(n, n), float(HALF_ALPHA) ** (1 / n)
        if abs(w - c) < FLOAT_CLEARANCE:
            ties.append(f"wilson-vs-cp n={n}")
        if w > c:
            w_above.append(n)

    bar0, e0, n0 = POWER_ASK
    extended = []
    for e in EXTENDED_ERRORS:
        n_min, rev = cp_min_n(bar0, e)
        reversals += [f"cp {dec(bar0, 2)} e={e} n={spans(rev)}"] if rev else []
        extended.append(str(n_min))
    lo_prev, hi_prev = cp_lower_bracket(n0 - 1 - e0, n0 - 1)
    lo_at, hi_at = cp_lower_bracket(n0 - e0, n0)
    # Round-25 falsify (RevRuleOfThree): scan the rule-of-three false PASS over 1..WINDOW, not only the
    # 1..40 display rows (at bar 0.95 it falsely passes n = 60..71).
    for n in range(1, WINDOW + 1):
        r3n = 1 - Fraction(RULE3, n)
        for bar in BARS:
            if r3n >= bar and not cp_passes(n, n, bar):
                false_pass[bar].append(n)
    derived = [
        ("power_ask_4dp", f"lower({n0 - 1 - e0}/{n0 - 1})={certify(lo_prev, hi_prev, 4)} "
                          f"lower({n0 - e0}/{n0})={certify(lo_at, hi_at, 4)} (half-even)"),
        (f"cp_min_n_bar{dec(bar0, 2)}_e0-{EXTENDED_ERRORS[-1]}", ",".join(extended)),
        ("tightest_crossing", min(gaps)[1]),
        ("rule3_exceeds_cp_e0_n", f"{spans(r3_above)} of 1-{ZERO_ERROR_NS[-1]} (1-3/n above 0.025^(1/n))"),
        ("rule3_false_PASS_e0_n", "; ".join(f"{dec(b, 2)}: {spans(false_pass[b])}" for b in BARS)
         + f" of 1-{WINDOW} (1-3/n >= bar while the CP verdict is INDETERMINATE)"),
        ("rule3_below_1sided95_n", f"{spans(r3_under_one_sided)} of 1-{ZERO_ERROR_NS[-1]} "
                                   "(1-3/n below 0.05^(1/n): it approximates the one-sided 95% bound)"),
        ("wilson_exceeds_cp_e0_n", f"{spans(w_above)} of 1-{WINDOW} (n/(n+z^2) above 0.025^(1/n))"),
    ]

    ok17, detail17 = power_ask_check(minima[(bar0, e0)])
    checks = [
        ("power_ask_n17", ok17, detail17),
        ("closed_form_e0", max_dev <= 1e-12,
         f"max |0.025^(1/n) - bisection| over n=1-{ZERO_ERROR_NS[-1]} = {max_dev:.1e} (<= 1e-12)"),
        ("two_derivations_agree", not disagree,
         "; ".join(disagree) or "exact-tail decision == bisection bracket at every min_n and min_n-1"),
        ("no_pass_reversal", not reversals,
         "; ".join(reversals) or f"every CP/rule3/Wilson minimum stays PASS through n={WINDOW}"),
        ("certified_digits", not unc, "; ".join(unc) or "every printed bound and gap is certified by its bracket"),
        ("float_clearance", not ties,
         "; ".join(ties) or f"Wilson crossings and Wilson-vs-CP comparisons clear the bar by >= {FLOAT_CLEARANCE:g}"),
    ]
    return {
        "min_n": min_rows,
        "zero_error": zero_rows,
        "derived": derived,
        "check": [(name, "PASS" if ok else "FAIL", detail) for name, ok, detail in checks],
        "power_ask_min_n": minima[(bar0, e0)],
    }


def render(res):
    lines = list(HEADER)
    for block in ("min_n", "zero_error", "derived", "check"):
        lines += ["", "\t".join(("table",) + COLUMNS[block])]
        lines += ["\t".join((block,) + tuple(row)) for row in res[block]]
    return "\n".join(lines) + "\n"


def summary(res):
    fails = sum(status != "PASS" for _, status, _ in res["check"])
    return (
        f"min_n_rows={len(res['min_n'])} zero_error_rows={len(res['zero_error'])} "
        f"checks={len(res['check'])} pass={len(res['check']) - fails} fail={fails} "
        f"power_ask_min_n={res['power_ask_min_n']}"
    )


def first_diff(want, have):
    """1-based number of the first differing line, or None when identical."""
    if want == have:
        return None
    a, b = want.splitlines(keepends=True), have.splitlines(keepends=True)
    return next((i for i, (x, y) in enumerate(zip(a, b), 1) if x != y), min(len(a), len(b)) + 1)


def selftest():
    """Positive controls must hold; every red mutation must be caught. Exit 0 iff both."""
    bar, e, n = POWER_ASK
    results = []
    found, _ = cp_min_n(bar, e)
    ok, detail = power_ask_check(found)
    results.append(("positive:power_ask_exact_rule", ok, detail))
    lo, hi = cp_lower_bracket(n, n)
    dev = abs(float(HALF_ALPHA) ** (1 / n) - float(lo))
    results.append(("positive:closed_form_n17", dev <= 1e-12, f"|0.025^(1/17) - bisection| = {dev:.1e}"))
    for (k, m), (want_lo, want_hi) in R_REFERENCE.items():
        lo, hi = cp_lower_bracket(k, m)
        ulo, uhi = cp_lower_bracket(m - k, m)  # CP upper(k, n) = 1 - p_L(n - k, n)
        got = (certify(lo, hi, 7), certify(1 - uhi, 1 - ulo, 7))
        results.append((f"positive:R_binom.test({k},{m})", got == (want_lo, want_hi),
                        f"got [{got[0]}, {got[1]}] want [{want_lo}, {want_hi}]"))

    mutants = (
        ("one-sided alpha 0.05 per tail", cp_min_n(bar, e, ONE_SIDED_HALF_ALPHA)[0]),
        ("rule of three 1-3/n", first_pass(lambda m: 1 - Fraction(RULE3, m) >= bar, 1)[0]),
        ("Wilson lower bound", first_pass(lambda m: wilson_lower(m - e, m) >= float(bar), e + 1)[0]),
        ("scan off by +1", found + 1),
        ("scan off by -1", found - 1),
    )
    for label, wrong in mutants:
        ok, _ = power_ask_check(wrong)
        results.append((f"red:{label}", not ok, f"mutant min_n={wrong} -> power_ask_n17 {'PASS' if ok else 'FAIL'}"))
    lo, hi = cp_lower_bracket(9, 10)
    perturbed = dec(Fraction(R_REFERENCE[(9, 10)][0]) + Fraction(1, 10**4), 7)
    results.append(("red:perturbed CP reference", certify(lo, hi, 7) != perturbed,
                    f"reference {perturbed} vs certified {certify(lo, hi, 7)}"))
    lo, hi = cp_lower_bracket(n, n, bits=8)
    results.append(("red:coarse 8-bit bracket", certify(lo, hi) is None,
                    f"[{dec(lo)}, {dec(hi)}] -> {'uncertified' if certify(lo, hi) is None else 'certified'}"))
    _, rev = first_pass(lambda m: m >= n and m % 2 == 1, 1)
    results.append(("red:non-monotone decision", bool(rev), f"reversals flagged at n={spans(rev[:3])}..."))
    text = render(build())
    mutated = text.replace(f"\t{n}\t{n}/{n}\t", f"\t{n - 1}\t{n - 1}/{n - 1}\t", 1)
    line = first_diff(text, mutated)
    results.append(("red:edited table cell", mutated != text and line is not None, f"drift caught at line {line}"))

    for name, ok, detail in results:
        print(f"selftest\t{'PASS' if ok else 'FAIL'}\t{name}\t{detail}")
    failed = sum(not ok for _, ok, _ in results)
    print(f"selftest_total={len(results)} pass={len(results) - failed} fail={failed}")
    return 0 if failed == 0 else 1


def main(argv=None):
    ap = argparse.ArgumentParser(description="Round-25 power table for the frozen two-sided 95% CP rule.")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", nargs="?", const=TSV_PATH, type=Path, metavar="FILE",
                      help=f"write the TSV (default: {TSV_PATH.name} beside this script)")
    mode.add_argument("--check", nargs="?", const=TSV_PATH, type=Path, metavar="FILE",
                      help="regenerate and byte-compare against FILE (default as --write)")
    mode.add_argument("--summary", action="store_true", help="print one counting line")
    mode.add_argument("--selftest", action="store_true", help="positive controls and red mutation runs")
    args = ap.parse_args(argv)
    if args.selftest:
        return selftest()
    res = build()
    text = render(res)
    status = 0 if all(status == "PASS" for _, status, _ in res["check"]) else 1
    if args.write:
        args.write.write_text(text, encoding="utf-8")
        print(f"wrote {args.write} ({len(text.splitlines())} lines); {summary(res)}")
    elif args.check:
        try:
            have = args.check.read_text(encoding="utf-8")
        except OSError as exc:
            print(f"drift: cannot read {args.check}: {exc}")
            return 1
        line = first_diff(text, have)
        if line is not None:
            print(f"drift: {args.check} differs from the regenerated table at line {line}")
            return 1
        print(f"no drift: {args.check} matches the regenerated table; {summary(res)}")
    elif args.summary:
        print(summary(res))
    else:
        sys.stdout.write(text)
    return status


if __name__ == "__main__":
    sys.exit(main())
