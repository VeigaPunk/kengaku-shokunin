def grade_r11(recs, md_text, runlog_text, rep, pids=None, seed_fn=None):
    """Re-derive every stored round-11 number from committed bytes.

    `pids`/`seed_fn` default to the preregistered n=64 (pids 201-264,
    seed 3000+pid*41); the fixture selftest passes a smaller pair set.
    """
    pids = list(R11_PIDS if pids is None else pids)
    seed_fn = r11_seed if seed_fn is None else seed_fn
    n = len(pids)

    truth_by_pid = _build_meta(recs, rep, pids, seed_fn)
    cells = _replay_graded(recs, rep, truth_by_pid)
    _check_descriptors(recs, rep, n, pids)
    _check_census(recs, rep, n)
    _check_summary(recs, runlog_text, rep, n)
    _check_analysis(recs, cells, truth_by_pid, md_text, rep, n, pids)
    return cells


def check_r11_ordering(rep, jsonl_path=None):
    """Preregistration discipline: bundle hashes + hash-before-first-request.

    Hermetic: relative paths from REPO_ROOT, sha256 recomputed in-process (no
    sha256sum subprocess). The jsonl is read (not passed) because the check's
    only consumer of it is the first-request_ts comparison.
    """
    lines = [l for l in read_text(R11_SHA).splitlines() if l.strip()]
    rep.eq("r11.ordering.sha_line_count", len(lines), len(R11_BUNDLE_FILES))
    seen = {}
    for line in lines:
        parts = line.split()
        if len(parts) < 2:
            rep.ok("r11.ordering.sha_line_parse", False, f"unparseable sha line: {line!r}")
            continue
        digest, rel = parts[0], parts[1]
        base = os.path.basename(rel)
        rep.ok(f"r11.ordering.sha_repo_relative.{base}",
               not os.path.isabs(rel) and rel.startswith("corpus/evidence/round11-power/"),
               f"sha line path {rel!r} is not repo-relative under round11-power/")
        full = os.path.join(REPO_ROOT, rel)
        if not os.path.isfile(full):
            rep.ok(f"r11.ordering.sha_file_present.{base}", False, f"missing bundle file {rel}")
            continue
        rep.eq(f"r11.ordering.sha256.{base}", digest, file_sha256(full))
        seen[base] = True
    rep.eq("r11.ordering.sha_file_set", sorted(seen), sorted(R11_BUNDLE_FILES))

    ord_text = read_text(R11_ORDERING)
    pre = re.search(r"^pre-hash\s+(\S+)\s*$", ord_text, re.M)
    post = re.search(r"^post-hash\s+(\S+)\s*$", ord_text, re.M)
    rep.ok("r11.ordering.pre_hash_present", pre is not None, "ordering.log has no 'pre-hash' line")
    rep.ok("r11.ordering.post_hash_present", post is not None, "ordering.log has no 'post-hash' line")

    path = jsonl_path or R11_JSONL
    recs = load_jsonl(path)
    stamped = [r for r in recs if "request_ts" in r and r.get("request_ts")]
    rep.ok("r11.ordering.requests_present", bool(stamped), "no records carry request_ts")
    if not stamped:
        return
    first_ts = min(r["request_ts"] for r in stamped)
    # request_ts has 1-second resolution and the run issues ~5 requests/s, so
    # records after the descriptors GET can share its second. The causal
    # ordering guarantee is granularity-independent: JSONL is append-ordered,
    # descriptors() issues the process's first request, so the first stamped
    # record in file order must be the descriptors record and must carry the
    # minimum timestamp. (L1 integration fix to the draft's all-in-first-second
    # form, which failed on the real bytes; recorded in INTEGRATOR-NOTES.md.)
    rep.ok("r11.ordering.first_request_is_descriptors",
           stamped[0].get("cell") == "descriptors" and stamped[0]["request_ts"] == first_ts,
           f"first stamped record in file order: {stamped[0].get('cell')} @ "
           f"{stamped[0]['request_ts']}; min request_ts {first_ts}")
    if post:
        rep.ok("r11.ordering.hash_precedes_first_request", post.group(1) <= first_ts,
               f"post-hash {post.group(1)} > first request_ts {first_ts}")
    if pre and post:
        rep.ok("r11.ordering.pre_le_post", pre.group(1) <= post.group(1),
               f"pre-hash {pre.group(1)} > post-hash {post.group(1)}")


def selftest_stats():
    """Re-prove the analytic t-table on known values (embedded assertions)."""
    checks = [
        ("t=2.0 df=63", 2.0, 63, 0.0500, 5e-4),
        ("t=1.999 df=60", 1.999, 60, 0.0502, 5e-4),
        ("t=0 df=63", 0.0, 63, 1.0, 1e-12),
    ]
    bad = []
    for name, t, df, want, tol in checks:
        got = t_two_sided_p(t, df)
        if abs(got - want) > tol:
            bad.append(f"{name}: p={got!r}, want {want} +/- {tol}")
    tc = t_crit(63, 0.05)
    if abs(tc - 1.9983405) > 1e-5:
        bad.append(f"t_crit(63,0.05)={tc!r}, want 1.9983405")
    for name, got, want in (("betai(0.5,0.5,0.5)", betai(0.5, 0.5, 0.5), 0.5),
                            ("betai(1,1,0.25)", betai(1.0, 1.0, 0.25), 0.25)):
        if abs(got - want) > 1e-12:
            bad.append(f"{name}={got!r}, want {want}")
    return bad


# ---------- pins ----------
def check_pins(paths, rep):
    for key, (algo, expected) in PINS.items():
        p = paths[key]
        if os.path.abspath(p) != os.path.abspath(DEFAULTS[key]):
            print(f"[pin] {key}: SKIPPED (overridden path, treated as mutated copy)")
            continue
        h = hashlib.new(algo)
        with open(p, "rb") as f:
            for chunk in iter(lambda: f.read(1 << 20), b""):
                h.update(chunk)
        rep.eq(f"pin.{key}.{algo}", expected, h.hexdigest())


# ---------- selftest ----------
def run_selftest():
    """Corrupt temp copies five ways (S1-S5); all must be caught, S0 control
    must pass, and S6 re-proves the analytic stats anchors."""
    results = []
    tmp = tempfile.mkdtemp(prefix="kengaku-grader-selftest-")
    try:
        clean = {}
        for key in DEFAULTS:
            # per-key unique tmp names: r8_runlog and r11_runlog share the
            # basename run.log (round-11 integration fix)
            clean[key] = os.path.join(tmp, key + "__" + os.path.basename(DEFAULTS[key]))
            with open(DEFAULTS[key], "rb") as src, open(clean[key], "wb") as dst:
                dst.write(src.read())
        r11args = ("--r11-jsonl", clean["r11_jsonl"], "--r11-md", clean["r11_md"],
                   "--r11-runlog", clean["r11_runlog"])
        import subprocess

        def run(*argv):
            p = subprocess.run([sys.executable, os.path.abspath(__file__), *argv],
                               capture_output=True, text=True)
            return p.returncode, p.stdout

        rc, out = run("--r8-jsonl", clean["r8_jsonl"], "--r8-runlog", clean["r8_runlog"],
                      "--r9-jsonl", clean["r9_jsonl"], "--r9-md", clean["r9_md"], *r11args)
        results.append(("S0 control (clean copies)", rc == 0 and "VERDICT: PASS" in out,
                        f"exit {rc}, expected 0"))

        # S1: flip one stored ok in the first r8 A-INC record with ok==true
        p1 = os.path.join(tmp, "m1.jsonl")
        flipped = False
        with open(clean["r8_jsonl"]) as f, open(p1, "w") as out:
            for line in f:
                r = json.loads(line)
                if not flipped and r.get("cell") == "A-INC" and r.get("ok") is True:
                    r["ok"] = False
                    line = json.dumps(r, separators=(",", ":")) + "\n"
                    flipped = True
                out.write(line)
        rc, out = run("--r8-jsonl", p1, "--r8-runlog", clean["r8_runlog"],
                      "--r9-jsonl", clean["r9_jsonl"], "--r9-md", clean["r9_md"], *r11args)
        results.append(("S1 stored-ok flip (record layer)",
                        rc == 1 and flipped and "MISMATCH r8.replay.A-INC.ok" in out,
                        f"exit {rc}, expected 1 + check-id r8.replay.A-INC.ok "
                        f"(flip applied: {flipped}, id fired: {'r8.replay.A-INC.ok' in out})"))

        # S2: edit one stored SUMMARY number in run.log
        p2 = os.path.join(tmp, "m2.log")
        txt = open(clean["r8_runlog"]).read()
        assert "A-INC: 7/10" in txt
        open(p2, "w").write(txt.replace("A-INC: 7/10", "A-INC: 8/10", 1))
        rc, out = run("--r8-jsonl", clean["r8_jsonl"], "--r8-runlog", p2,
                      "--r9-jsonl", clean["r9_jsonl"], "--r9-md", clean["r9_md"], *r11args)
        results.append(("S2 run.log SUMMARY edit (summary layer)",
                        rc == 1 and "MISMATCH r8.summary.A-INC" in out,
                        f"exit {rc}, expected 1 + check-id r8.summary.A-INC "
                        f"(id fired: {'r8.summary.A-INC' in out})"))

        # S3: bump the first digit inside the last fenced JSON block of the
        #     first r9 A-MONO record's raw (re-parse layer)
        p3 = os.path.join(tmp, "m3.jsonl")
        done = False
        with open(clean["r9_jsonl"]) as f, open(p3, "w") as out:
            for line in f:
                r = json.loads(line)
                if not done and r.get("cell") == "A-MONO":
                    raw = r["raw"]
                    blocks = list(re.finditer(r"```(?:json)?\s*\n(.*?)```", raw, re.S))
                    if blocks:
                        b = blocks[-1]
                        inner = b.group(1)
                        dm = re.search(r"\d", inner)
                        if dm:
                            newdigit = str((int(dm.group(0)) + 1) % 10)
                            newinner = inner[:dm.start()] + newdigit + inner[dm.end():]
                            raw = raw[:b.start(1)] + newinner + raw[b.end(1):]
                            r["raw"] = raw
                            line = json.dumps(r, separators=(",", ":")) + "\n"
                            done = True
                out.write(line)
        rc, out = run("--r8-jsonl", clean["r8_jsonl"], "--r8-runlog", clean["r8_runlog"],
                      "--r9-jsonl", p3, "--r9-md", clean["r9_md"], *r11args)
        results.append(("S3 raw-digit bump (re-parse layer)",
                        rc == 1 and done and "MISMATCH r9.replay.A-MONO.got" in out,
                        f"exit {rc}, expected 1 + check-id r9.replay.A-MONO.got "
                        f"(mutation applied: {done}, id fired: {'r9.replay.A-MONO.got' in out})"))

        # S4: flip one stored ok in the first r11 A-CKPT4710 graded record
        p4 = os.path.join(tmp, "m4.jsonl")
        flipped4 = False
        with open(clean["r11_jsonl"]) as f, open(p4, "w") as out:
            for line in f:
                r = json.loads(line)
                if not flipped4 and r.get("cell") == "A-CKPT4710" and r.get("ok") is True:
                    r["ok"] = False
                    line = json.dumps(r, separators=(",", ":")) + "\n"
                    flipped4 = True
                out.write(line)
        rc, out = run("--r8-jsonl", clean["r8_jsonl"], "--r8-runlog", clean["r8_runlog"],
                      "--r9-jsonl", clean["r9_jsonl"], "--r9-md", clean["r9_md"],
                      "--r11-jsonl", p4, "--r11-md", clean["r11_md"],
                      "--r11-runlog", clean["r11_runlog"])
        results.append(("S4 r11 stored-ok flip (record layer)",
                        rc == 1 and flipped4 and "MISMATCH r11.replay.A-CKPT4710.ok" in out,
                        f"exit {rc}, expected 1 + check-id r11.replay.A-CKPT4710.ok "
                        f"(flip applied: {flipped4}, id fired: {'r11.replay.A-CKPT4710.ok' in out})"))

        # S5: bump the numerator of the r11 run.log SUMMARY cell line
        p5 = os.path.join(tmp, "m5.log")
        txt5 = open(clean["r11_runlog"]).read()
        assert "A-CKPT4710: 29/64" in txt5
        open(p5, "w").write(txt5.replace("A-CKPT4710: 29/64", "A-CKPT4710: 30/64", 1))
        rc, out = run("--r8-jsonl", clean["r8_jsonl"], "--r8-runlog", clean["r8_runlog"],
                      "--r9-jsonl", clean["r9_jsonl"], "--r9-md", clean["r9_md"],
                      "--r11-jsonl", clean["r11_jsonl"], "--r11-md", clean["r11_md"],
                      "--r11-runlog", p5)
        results.append(("S5 r11 run.log SUMMARY edit (summary layer)",
                        rc == 1 and "MISMATCH r11.summary.A-CKPT4710" in out,
                        f"exit {rc}, expected 1 + check-id r11.summary.A-CKPT4710 "
                        f"(id fired: {'r11.summary.A-CKPT4710' in out})"))

        # S6: analytic stats anchors (betai t-CDF known values + t_crit(63))
        bad = selftest_stats()
        results.append(("S6 stats anchors (betai/t_crit known values)", not bad,
                        "; ".join(bad) if bad else "all known-value assertions hold"))
    finally:
        import shutil
        shutil.rmtree(tmp, ignore_errors=True)
    all_ok = True
    for name, passed, detail in results:
        print(f"[selftest] {'PASS' if passed else 'FAIL'} {name}: {detail}")
        all_ok = all_ok and passed
    print(f"[selftest] {'ALL PASS' if all_ok else 'FAILURES PRESENT'}")
    return 0 if all_ok else 1


# ---------- main ----------
def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--selftest", action="store_true",
                    help="corrupt temp copies; exit 0 only if every corruption is caught")
    ap.add_argument("--r8-jsonl", default=DEFAULTS["r8_jsonl"])
    ap.add_argument("--r8-runlog", default=DEFAULTS["r8_runlog"])
    ap.add_argument("--r9-jsonl", default=DEFAULTS["r9_jsonl"])
    ap.add_argument("--r9-md", default=DEFAULTS["r9_md"])
    ap.add_argument("--r11-jsonl", default=DEFAULTS["r11_jsonl"])
    ap.add_argument("--r11-md", default=DEFAULTS["r11_md"])
    ap.add_argument("--r11-runlog", default=DEFAULTS["r11_runlog"])
    args = ap.parse_args(argv)

    if args.selftest:
        sys.exit(run_selftest())

    paths = {"r8_jsonl": args.r8_jsonl, "r8_runlog": args.r8_runlog,
             "r9_jsonl": args.r9_jsonl, "r9_md": args.r9_md,
             "r11_jsonl": args.r11_jsonl, "r11_md": args.r11_md,
             "r11_runlog": args.r11_runlog}
    for key, p in paths.items():
        if not os.path.isfile(p):
            die(f"{key}: no such file: {p}")
    for p in (R9_PRED, R9_PRED_SHA, R9_ORDERING, R11_PRED, R11_SHA, R11_ORDERING):
        if not os.path.isfile(p):
            die(f"missing sidecar file: {p}")

    rep = Report()
    check_pins(paths, rep)
    r8_recs = load_jsonl(paths["r8_jsonl"])
    r9_recs = load_jsonl(paths["r9_jsonl"])
    r8_summ_recomp, r8_summ_stored = grade_r8(r8_recs, read_text(paths["r8_runlog"]), rep)
    grade_r9(r9_recs, read_text(paths["r9_md"]), rep, r8_summ_recomp, r8_summ_stored)
    r11_recs = load_jsonl(paths["r11_jsonl"])
    grade_r11(r11_recs, read_text(paths["r11_md"]), read_text(paths["r11_runlog"]), rep)
    check_r11_ordering(rep, jsonl_path=paths["r11_jsonl"])

    for line in rep.mismatches:
        print(line)
    print(f"CHECKS n={rep.checks} mismatches={len(rep.mismatches)} "
          f"errata_pinned={len(ERRATA)}")
    print("VERDICT: " + ("PASS — stored evidence fully re-derives offline"
                         if not rep.mismatches else "FAIL"))
    return 0 if not rep.mismatches else 1


if __name__ == "__main__":
    try:
        sys.exit(main())
    except SystemExit:
        raise
    except Exception as e:  # any unexpected crash is an input/env problem
        print(f"grader: INPUT ERROR: {type(e).__name__}: {e}", file=sys.stderr)
        sys.exit(2)
